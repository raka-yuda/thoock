import "server-only";
import { GoogleGenAI } from "@google/genai";
import {
  ADOBE_STOCK_CATEGORIES,
  normalizeAdobeCategory,
} from "@/lib/domain/adobe-categories";
import {
  normalizeFilename,
  normalizeKeywords,
  type AssetMetadata,
} from "@/lib/domain/metadata";
import type { MetadataGenerationProvider } from "./contracts";

export class BriefMetadataProvider implements MetadataGenerationProvider {
  readonly id = "brief-metadata";
  readonly label = "Brief metadata plan";

  async generate(input: {
    briefName: string;
    prompt: string;
    filenameHint: string;
    briefPlan?: {
      title: string;
      category: string;
      language: string;
      keywords: string[];
      fictionalPeopleProperty: boolean;
      notes: string;
    };
  }): Promise<AssetMetadata> {
    const plan = input.briefPlan;
    const category = normalizeAdobeCategory(plan?.category);
    const keywords = normalizeKeywords(plan?.keywords ?? []);
    if (!plan?.title.trim() || !category || keywords.length < 5)
      throw new Error(
        "Complete the brief metadata title, Adobe category, and at least 5 ordered keywords before approval.",
      );
    return {
      filename: normalizeFilename(input.filenameHint),
      title: plan.title.trim(),
      category,
      language: plan.language.trim() || "en",
      keywords,
      generativeAi: true,
      fictionalPeopleProperty: plan.fictionalPeopleProperty,
      internalNotes: plan.notes,
    };
  }
}

export class DeterministicMetadataProvider implements MetadataGenerationProvider {
  readonly id = "mock-metadata";
  readonly label = "Deterministic mock metadata";
  async generate(input: {
    briefName: string;
    prompt: string;
    filenameHint: string;
  }): Promise<AssetMetadata> {
    const terms = normalizeKeywords(`${input.briefName},${input.prompt}`)
      .filter((keyword) => keyword.length > 2)
      .slice(0, 18);
    while (terms.length < 5)
      terms.push(
        ["commercial", "creative", "background", "copy space", "modern"][
          terms.length
        ],
      );
    return {
      filename: normalizeFilename(input.filenameHint),
      title: input.briefName
        .replace(/\b(?:generative ai|4k|8k|prompt)\b/gi, "")
        .trim()
        .slice(0, 70),
      category: "3",
      language: "en",
      keywords: normalizeKeywords(terms),
      generativeAi: true,
      fictionalPeopleProperty: false,
      internalNotes:
        "Generated by deterministic mock provider. Review before export.",
    };
  }
}

export class GeminiMetadataProvider implements MetadataGenerationProvider {
  readonly id = "gemini-metadata";
  readonly label = "Gemini metadata";
  async generate(input: {
    briefName: string;
    prompt: string;
    filenameHint: string;
  }): Promise<AssetMetadata> {
    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) throw new Error("GEMINI_API_KEY is not configured.");
    const ai = new GoogleGenAI({ apiKey });
    const response = await ai.models.generateContent({
      model: process.env.GEMINI_TEXT_MODEL ?? "gemini-2.5-flash",
      contents: `Return JSON metadata for an Adobe Stock image. Title max 70 characters, no model or artist names. Return 10 to 35 ordered, commercially meaningful English keyword strings using nouns, adjectives, relevant action words, visual concepts, buyer uses, and locations. Exclude articles, conjunctions, prepositions, pronouns, and generic filler words. Category must be the numeric string for exactly one option: ${ADOBE_STOCK_CATEGORIES.map((item) => `${item.code}=${item.label}`).join(", ")}. Brief: ${input.briefName}. Visual prompt: ${input.prompt}`,
      config: { responseMimeType: "application/json" },
    });
    const value = JSON.parse(response.text ?? "{}") as {
      title?: string;
      category?: string | number;
      keywords?: string[];
      fictionalPeopleProperty?: boolean;
    };
    return {
      filename: normalizeFilename(input.filenameHint),
      title: (value.title ?? input.briefName).slice(0, 70),
      category: normalizeAdobeCategory(value.category) ?? "3",
      language: "en",
      keywords: normalizeKeywords(value.keywords ?? input.prompt),
      generativeAi: true,
      fictionalPeopleProperty: value.fictionalPeopleProperty ?? false,
      internalNotes:
        "AI-generated metadata. Human editing and validation are required.",
    };
  }
}
